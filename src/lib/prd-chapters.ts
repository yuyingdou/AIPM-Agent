/**
 * 组装最终 PRD 文档
 */
export function assemblePrd(
  docTitle: string,
  author: string,
  date: string,
  groupResults: (string | null)[]
): string {
  const parts: string[] = [];

  // 文档标题
  parts.push(docTitle);
  parts.push("");

  // 更新记录（代码生成，非 LLM）
  parts.push("## 更新记录");
  parts.push("");
  parts.push("| 操作人 | 更新时间 | 变更说明 |");
  parts.push("|--------|----------|----------|");
  parts.push(`| ${author} | ${date} | 初始版本 |`);
  parts.push("");

  // 拼接 5 组章节内容
  for (let i = 0; i < groupResults.length; i++) {
    const content = groupResults[i];
    if (content) {
      parts.push(content.trim());
      parts.push("");
    } else {
      parts.push(`<!-- ⚠️ 第 ${i + 1} 组章节生成失败，请人工补充 -->`);
      parts.push("");
    }
  }

  return parts.join("\n");
}
