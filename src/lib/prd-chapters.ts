/**
 * 为每个章节组生成独立的 prompt
 */
export function chapterPrompt(
  groupId: string,
  groupTitle: string,
  chapters: string,
  extractedInfo: string,
  docTitle: string,
  searchResults: string
): string {
  return `# 任务：只生成以下章节的 PRD 内容

你是资深 AI 产品经理。你只负责生成 **${groupTitle}** 部分（${chapters}）。

## 产品信息

${extractedInfo}

${searchResults ? `## 网络搜索结果\n${searchResults}` : ""}

## 文档上下文

完整 PRD 标题：${docTitle}
你负责的部分：${groupTitle}

## 规则

1. 输出你负责的章节，从 \`##\` 标题开始
2. 用 Markdown 格式，包含所有规定的表格和 Mermaid 图表
3. 表格列数和列名必须与下面模板一致
4. Mermaid 图必须写完整语法（不能只有注释占位）
5. 全程中文
6. 信息不足的标 \`<!-- 待确认 -->\`

## ${groupTitle} 模板（必须遵循的结构）

${getGroupTemplate(groupId)}

现在开始输出你的章节：`;
}

